// Regenerates src/generated/registry.ts from campaigns/*/brand.json + campaigns/*/ads/*.json
// and validates every spec. Run after adding or deleting a spec file.
import fs from 'node:fs';
import path from 'node:path';
import {STUDIO, CAMPAIGNS, listCampaigns, listAdFiles, loadAll, timeline} from './lib.mjs';

const target = path.join(STUDIO, 'src', 'generated', 'registry.ts');
const rel = (p) => path.relative(path.dirname(target), p).split(path.sep).join('/');

const lines = ['// AUTO-GENERATED by scripts/sync-specs.mjs - do not edit by hand.', ''];
const entries = [];
listCampaigns().forEach((slug, ci) => {
  lines.push(`import brand${ci} from '${rel(path.join(CAMPAIGNS, slug, 'brand.json'))}';`);
  const ads = listAdFiles(slug).map((f, ai) => {
    lines.push(`import c${ci}a${ai} from '${rel(f)}';`);
    return `c${ci}a${ai}`;
  });
  entries.push(`  {slug: '${slug}', brand: brand${ci} as unknown, ads: [${ads.join(', ')}] as unknown[]},`);
});
lines.push('', 'export const CAMPAIGNS: {slug: string; brand: unknown; ads: unknown[]}[] = [', ...entries, '];', '');
fs.mkdirSync(path.dirname(target), {recursive: true});
fs.writeFileSync(target, lines.join('\n'));

let bad = 0;
for (const a of loadAll()) {
  if (a.error) {
    bad++;
    console.log(`✗ ${a.slug}/${a.id}  ${a.error}`);
  } else {
    const tl = timeline(a.spec);
    console.log(`✓ ${a.slug}/${a.id}  ${(tl.total / tl.fps).toFixed(1)}s  ${a.spec.scenes.length} scenes  [${a.spec.formats.join(', ')}]`);
  }
}
console.log(`\nregistry -> ${path.relative(process.cwd(), target)}`);
if (bad) process.exitCode = 1;
